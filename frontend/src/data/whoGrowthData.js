// Helper to get interpolated percentile value for any age
export function getPercentileForAge(data, ageMonths) {
    if (ageMonths <= data[0].months) return data[0];
    if (ageMonths >= data[data.length - 1].months) return data[data.length - 1];

    // Find surrounding data points
    let lower = data[0];
    let upper = data[1];
    for (let i = 0; i < data.length - 1; i++) {
        if (data[i].months <= ageMonths && data[i + 1].months >= ageMonths) {
            lower = data[i];
            upper = data[i + 1];
            break;
        }
    }

    // Linear interpolation
    const t = (ageMonths - lower.months) / (upper.months - lower.months);
    return {
        months: ageMonths,
        p3: lower.p3 + t * (upper.p3 - lower.p3),
        p15: lower.p15 + t * (upper.p15 - lower.p15),
        p50: lower.p50 + t * (upper.p50 - lower.p50),
        p85: lower.p85 + t * (upper.p85 - lower.p85),
        p97: lower.p97 + t * (upper.p97 - lower.p97),
    };
}
